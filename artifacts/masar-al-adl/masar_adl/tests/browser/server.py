"""Disposable browser-test server; never imports the live app or SQL configuration."""
import sys
from pathlib import Path
from tempfile import TemporaryDirectory

import uvicorn

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from app.config import Settings
from app.documents import sample_pdf_bytes
from app.main import create_app
from app.repositories import DemoRepository


if __name__ == "__main__":
    with TemporaryDirectory(prefix="masar-browser-TEST-") as temporary:
        root = Path(temporary)
        # Inject the literal TEST repository, not build_repository(auto/sqlserver).
        repo = DemoRepository()
        assert all(u["national_id"].startswith("TEST-") for u in repo.select("users"))
        settings = Settings(data_mode="demo", storage_dir=root / "storage", log_dir=root / "logs",
                            pdf_storage_backend="local")
        app = create_app(settings, repo=repo)
        # A real, readable PDF generated by the application's existing demo renderer.
        # Served only by this disposable test process, never by the application.
        from starlette.responses import Response
        from starlette.routing import Route

        async def fixture_pdf(request):
            if request.query_params.get("pages") == "2":
                from io import BytesIO
                from reportlab.pdfgen import canvas
                buffer = BytesIO()
                fixture = canvas.Canvas(buffer, invariant=1)
                for number in (1, 2):
                    fixture.setFont("MasarArabic", 16)
                    fixture.drawString(60, 740, f"TEST ONLY — Page {number} of 2")
                    fixture.showPage()
                fixture.save()
                return Response(buffer.getvalue(), media_type="application/pdf")
            return Response(sample_pdf_bytes("TEST browser regression"), media_type="application/pdf")

        app.router.routes.append(Route("/__TEST_fixture.pdf", fixture_pdf))
        uvicorn.run(app, host="127.0.0.1", port=8765, access_log=False)
